const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fixture = require('./offline-fixture.cjs');
const f = fixture(), { context: ctx, token } = f;
const device = crypto.randomUUID();
const grant = f.api('offlinegrant', { token, device });
assert.equal(grant.ok, true);
assert.ok(grant.expiresAt > Date.now());
assert.equal(f.api('offlineresume', { ...grant, secret: 'wrong' }).ok, false);
assert.equal(f.api('offlineresume', grant).ok, true);
const operationId = crypto.randomUUID();
const create = { operationId, action: 'save', baseVersion: '', data: { id: 'OFF-' + operationId, codigo: 'PRUEBA-OFFLINE', fecha: '2026-10-26', peaje: 'OTRO', total: 1000, estado: 'APROBADO' } };
const write = operation => f.api('offlinemutate', { token, operation: JSON.stringify(operation) });
assert.equal(f.api('offlinemutate', { operation: create }).ok, false);
const first = write(create);
assert.equal(first.ok, true);
assert.equal(first.row.peaje, 'FRAGUA', 'Server controls the toll');
assert.equal(write(create).replayed, true);
assert.equal(f.sheets.get('PLANILLAS').rows.length, 2);
assert.equal(write({ ...create, data: { ...create.data, total: 2000 } }).code, 'OFFLINE_CONFLICT');
const duplicateId = crypto.randomUUID();
assert.equal(write({ ...create, operationId: duplicateId, data: { ...create.data, id: 'OFF-' + duplicateId } }).code, 'CODIGO_DUPLICADO');
const update = { operationId: crypto.randomUUID(), action: 'update', baseVersion: ctx.versionPlanillaOffline_(first.row), data: { ...first.row, total: 2000 } };
f.advance(100);
const updated = write(update);
assert.equal(updated.ok, true);
assert.equal(updated.row.total, 2000);
assert.equal(write({ ...update, operationId: crypto.randomUUID(), data: { ...updated.row, total: 3000 } }).code, 'OFFLINE_CONFLICT', 'Stale update cannot overwrite current data');
f.advance(100);
const partial = { operationId: crypto.randomUUID(), action: 'update', baseVersion: ctx.versionPlanillaOffline_(updated.row), data: { ...updated.row, total: 4000 } };
f.failAfterWrite();
assert.equal(write(partial).ok, false);
assert.equal(f.sheets.get('PLANILLAS').rows[1][ctx.headerIndex_('total') - 1], 4000);
const replay = write(partial);
assert.equal(replay.ok, true, 'Retry recognizes an applied row after interrupted confirmation');
assert.equal(f.sheets.get('PLANILLAS').rows.length, 2);
f.advance(100);
assert.equal(write({ operationId: crypto.randomUUID(), action: 'delete', baseVersion: ctx.versionPlanillaOffline_(replay.row), data: replay.row }).row.estado, 'ANULADA');
const user = f.users.get('operador');
const reservedId = crypto.randomUUID();
const reserved = { ...create, operationId: reservedId, data: { ...create.data, id: 'OFF-' + reservedId, codigo: 'RESERVA' } };
f.failBeforeWrite();
assert.equal(write(reserved).ok, false);
const competingId = crypto.randomUUID();
assert.equal(write({ ...reserved, operationId: competingId, data: { ...reserved.data, id: 'OFF-' + competingId } }).ok, true);
assert.equal(write(reserved).code, 'CODIGO_DUPLICADO', 'A reserved but unwritten result must recheck uniqueness on retry');
user.ESTADO = 'INACTIVO'; assert.equal(f.api('offlineresume', grant).ok, false);
user.ESTADO = 'ACTIVO'; user.ROL = 'ADMIN'; assert.equal(f.api('offlineresume', grant).ok, false);
user.ROL = 'PEAJE'; user.CONTRASENA = 'changed'; assert.equal(f.api('offlineresume', grant).ok, false);
user.CONTRASENA = 'hash-password'; f.advance(8 * 86400000); assert.equal(f.api('offlineresume', grant).ok, false);
console.log('OK: offline grants, expiry, revocation, scoped permissions, idempotent creates/updates/deletes, stale versions, duplicates and interrupted confirmation.');
